# METRIC MAPPER (fuzzy substring matching)
# ===========================================================================
class MetricMapper:
    """Maps human words to database column names.

    The brief asks for *substring containment* fuzzy matching: if the extracted
    context contains ANY dictionary key anywhere inside it, that key wins -
    regardless of prefixes or suffixes. So all of these map to ``active_users``:

        "users", "active users", "our MAU", "user_count", "#users"

    We additionally score by keyword length and by how close the keyword sits
    to the number, because a sentence can mention several metrics at once.
    """

    def __init__(self, mapping: Optional[Dict[str, str]] = None,
                 regions: Optional[RegionRegistry] = None,
                 aliases: Optional[Dict[str, str]] = None) -> None:
        self.mapping = dict(mapping or METRIC_KEYWORD_MAP)
        # User-taught corrections from the smart-suggest feature. They are
        # merged in at HIGHEST priority so a learned alias always wins over a
        # shipped default keyword.
        self.aliases: Dict[str, str] = {
            str(k).strip().lower(): str(v)
            for k, v in (aliases or {}).items() if str(k).strip()
        }
        self.keys = sorted(self.mapping.keys(), key=len, reverse=True)
        # Region vocabulary is injected, never hardcoded. An empty registry
        # simply disables region detection.
        self.regions = regions if regions is not None else DEFAULT_REGION_REGISTRY

    def set_aliases(self, aliases: Dict[str, str]) -> None:
        """Refresh learned corrections without rebuilding the mapper."""
        self.aliases = {
            str(k).strip().lower(): str(v)
            for k, v in (aliases or {}).items() if str(k).strip()
        }

    def register_metrics(self, names: Iterable[str]) -> None:
        """Teach the mapper about metrics discovered at runtime.

        Two sources feed this:
          * ``SELECT DISTINCT metric_name`` from the database, so a warehouse
            column you never added to METRIC_KEYWORD_MAP is still recognised.
          * derived-metric keys from ``config.json``.

        CRITICAL ORDERING DETAIL: these names are inserted so that LONGER keys
        win. Without that, a derived metric called ``total_revenue`` would be
        shadowed by the built-in ``revenue`` keyword (because "revenue" is a
        substring of the phrase "total revenue") and the formula would never
        fire. Sorting the key list by descending length fixes it globally.
        """
        for name in names or []:
            text = str(name).strip()
            if not text:
                continue
            key = text.lower()
            # Both the raw form ("total_revenue") and a spaced form
            # ("total revenue") should match prose.
            for variant in {key, key.replace("_", " "), key.replace("-", " ")}:
                if variant and variant not in self.mapping:
                    self.mapping[variant] = text
        self.keys = sorted(self.mapping.keys(), key=len, reverse=True)

    def map_text(self, text: str) -> Tuple[Optional[str], str]:
        """Return ``(db_column, matched_keyword)`` or ``(None, "")``."""
        if not text:
            return None, ""
        haystack = text.lower()

        # Learned aliases win outright - the user explicitly taught us these.
        exact = self.aliases.get(haystack.strip())
        if exact:
            return exact, haystack.strip()

        for key in self.keys:
            if key in haystack:
                return self.mapping[key], key
        return None, ""

    @staticmethod
    def _clause_penalty(text: str, pos_a: int, pos_b: int) -> float:
        """Cost of the clause boundaries lying between two positions.

        Natural language groups a number with the metric word in its OWN
        clause. In::

            "revenue was $4.8M, and the churn rate held at 2.3%"

        the word "churn" is only a few characters further from 4.8M than
        "revenue" is - raw distance alone would get it wrong. Counting the
        comma and the "and" in between, and charging for them, fixes it.
        """
        low, high = (pos_a, pos_b) if pos_a <= pos_b else (pos_b, pos_a)
        between = text[int(low):int(high)]
        return (CLAUSE_PENALTY * len(CLAUSE_BOUNDARY_PATTERN.findall(between))
                + SENTENCE_PENALTY * len(SENTENCE_BOUNDARY_PATTERN.findall(between)))

    def map_with_position(self, context: str, number_pos: int) -> Tuple[Optional[str], str]:
        """Pick the keyword that most plausibly names *this* number.

        Score = distance to the number
              + penalty for every clause boundary crossed
              - a bonus for keyword length (specific beats generic)

        Lowest score wins. Example: "Revenue was 4.8M while users hit 2100"
        gives ``revenue`` for 4.8M and ``active_users`` for 2100.
        """
        if not context:
            return None, ""
        haystack = context.lower()
        best: Optional[Tuple[float, str, str]] = None

        for key in self.keys:
            start = 0
            while True:
                idx = haystack.find(key, start)
                if idx == -1:
                    break
                centre = idx + len(key) / 2
                distance = abs(centre - number_pos)
                score = (distance
                         + self._clause_penalty(haystack, centre, number_pos)
                         - (len(key) * 0.75))
                if best is None or score < best[0]:
                    best = (score, self.mapping[key], key)
                start = idx + 1

        if best is None:
            return None, ""
        return best[1], best[2]

    def detect_region(self, text: str) -> Optional[str]:
        """Find the first known region label in ``text``.

        The vocabulary comes from :class:`RegionRegistry` - i.e. from YOUR
        database - not from any hardcoded list of continents.
        """
        if not text or self.regions.is_empty:
            return None
        for label, _start, _end in self.regions.finditer(text):
            return label
        return None

    def detect_region_with_position(self, context: str,
                                    number_pos: int) -> Optional[str]:
        """Pick the region label *closest to the number*, as we do for metrics.

        Why this matters: a sentence may name two regions::

            "Region_A active users hit 984.5k and Global revenue was $4.8M"

        A naive first-match scan would stamp Region_A onto the revenue figure
        and then fail to find the row. Distance scoring (plus the clause and
        sentence penalties) attaches each label to the number it belongs to,
        which is what a human reader does.
        """
        if not context or self.regions.is_empty:
            return None
        haystack = context.lower()
        best: Optional[Tuple[float, str]] = None

        for label, start, end in self.regions.finditer(haystack):
            centre = start + (end - start) / 2
            score = (abs(centre - number_pos)
                     + self._clause_penalty(haystack, centre, number_pos)
                     - ((end - start) * 0.5))
            if best is None or score < best[0]:
                best = (score, label)

        # Confidence floor: a region word that is far away, or on the other
        # side of a sentence break, tells us nothing about THIS number. Return
        # None so the lookup runs region-agnostic instead of being confidently
        # wrong.
        if best is None or best[0] > REGION_SCORE_LIMIT:
            return None
        return best[1]


