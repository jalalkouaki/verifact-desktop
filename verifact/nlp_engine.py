@dataclass
class Timeframe:
    """A resolved point in time. Any field may be ``None`` (= unspecified)."""

    quarter: Optional[str] = None      # "Q1".."Q4"
    year: Optional[int] = None
    month: Optional[int] = None
    label: str = ""                    # the original human text, e.g. "last quarter"
    inferred: bool = False             # True when we defaulted rather than read it

    def describe(self) -> str:
        """Short, unambiguous string for the results table.

        Always shows the RESOLVED period (e.g. "Q3 2024") rather than only the
        words the user typed, because "last quarter" alone tells the reader of
        a report nothing. Where the resolution came from an inference rather
        than the text we say so.
        """
        parts: List[str] = []
        if self.quarter:
            parts.append(self.quarter)
        elif self.month:
            parts.append(f"M{self.month:02d}")
        if self.year:
            parts.append(str(self.year))

        resolved = " ".join(parts)
        if not resolved:
            return "unspecified"
        if self.inferred:
            return f"{resolved} (assumed)"
        # Show the original wording too when it differs from the resolution,
        # e.g. 'Q3 2024 (last quarter)'.
        if self.label and self.label.strip().lower() not in resolved.lower():
            return f"{resolved} ({self.label.strip()})"
        return resolved


@dataclass
class Claim:
    """One numeric assertion pulled out of the source text."""

    raw_value: str                      # exactly as written: "984.5k"
    value: float                        # parsed float: 984.5
    scale: float = 1.0                  # 1000.0 when the text said "k"
    is_percent: bool = False
    is_currency: bool = False
    context: str = ""                   # surrounding sentence / window
    metric_text: str = ""               # the words we think name the metric
    metric_column: Optional[str] = None # mapped DB column, None = unmapped
    region: Optional[str] = None
    timeframe: Timeframe = field(default_factory=Timeframe)
    char_start: int = 0
    char_end: int = 0
    line_no: int = 0                    # 1-based line within the source
    source_label: str = ""              # e.g. "row 12" or "key: revenue"
    extraction_backend: str = "regex"
    #: True when the token could legitimately be read two ways ("1,234").
    ambiguous_format: bool = False
    #: Other defensible readings of the same token, already scaled. The
    #: verifier tries these before failing a claim, so an ambiguous separator
    #: can never cause a false FAIL.
    alternative_values: List[float] = field(default_factory=list)
    #: Which convention the containing document appeared to use.
    number_profile: str = "unknown"

    def scaled_value(self) -> float:
        """The claim value expressed in base units (984.5k -> 984500.0)."""
        return self.value * self.scale


# ===========================================================================
# TIMEFRAME PARSER
# ===========================================================================
class TimeframeParser:
    """Converts natural-language date fragments into (quarter, year, month).

    The brief calls out these behaviours explicitly and they are implemented
    below:

      * "last quarter"   -> Q3, 2024   (relative to the demo reference point)
      * "January 2025"   -> month=1, year=2025, quarter=Q1
      * "Q4"             -> quarter=Q4, year = current year (default 2024)
      * nothing at all   -> caller substitutes the newest period in the DB

    The "demo reference point" lives in config.json under
    ``verification.demo_reference_year`` / ``demo_reference_quarter`` so you can
    switch to the real system clock by setting the year to 0.
    """

    def __init__(self, reference_year: int = 2024, reference_quarter: int = 4) -> None:
        if not reference_year:  # 0 / None means "use the real clock"
            now = datetime.now()
            reference_year = now.year
            reference_quarter = (now.month - 1) // 3 + 1
        self.ref_year = int(reference_year)
        self.ref_quarter = int(reference_quarter)

    # -- helpers ----------------------------------------------------------
    @staticmethod
    def _normalise_year(raw: Optional[str], fallback: int) -> int:
        """Turn '24', '2024' or None into a full 4-digit year."""
        if not raw:
            return fallback
        digits = str(raw).strip()
        if len(digits) == 2:
            return 2000 + int(digits)
        try:
            return int(digits)
        except ValueError:
            return fallback

    def _shift_quarter(self, delta: int) -> Tuple[str, int]:
        """Move N quarters away from the reference point, rolling the year."""
        index = (self.ref_quarter - 1) + delta
        year = self.ref_year + index // 4
        quarter = (index % 4) + 1
        return f"Q{quarter}", year

    # -- the public entry point -------------------------------------------
    def parse(self, text: str) -> Timeframe:
        """Scan ``text`` and return the best timeframe we can find.

        Detection order is deliberate: the most explicit forms are checked
        first so "Q1 FY2025" is not mistaken for a bare year.
        """
        if not text:
            return Timeframe()

        lowered = text.lower()

        # --- 1. Explicit quarter, e.g. "Q3 2024" / "Q3'24" / "Q3" ---------
        m = QUARTER_PATTERN.search(text)
        if m:
            quarter = f"Q{m.group(1)}"
            # A year may sit right after the quarter, or anywhere in the text.
            year = self._normalise_year(m.group(2), 0)
            if not year:
                y = YEAR_PATTERN.search(text)
                fy = FY_PATTERN.search(text)
                if y:
                    year = int(y.group(1))
                elif fy:
                    year = self._normalise_year(fy.group(1), self.ref_year)
                else:
                    year = self.ref_year
            return Timeframe(quarter=quarter, year=year, label=m.group(0).strip())

        # --- 2. Half year, e.g. "H1 2025" --------------------------------
        m = HALF_PATTERN.search(text)
        if m:
            half = int(m.group(1))
            year = self._normalise_year(m.group(2), 0) or (
                int(YEAR_PATTERN.search(text).group(1))
                if YEAR_PATTERN.search(text) else self.ref_year
            )
            # H1 covers Q1+Q2; we represent it by its *closing* quarter so a
            # lookup lands on real data rather than nothing.
            return Timeframe(quarter="Q2" if half == 1 else "Q4",
                             year=year, label=m.group(0).strip())

        # --- 3. Month name, e.g. "January 2025" / "Feb" -------------------
        m = MONTH_PATTERN.search(text)
        if m:
            month = MONTH_NAMES[m.group(1).lower()]
            year = self._normalise_year(m.group(2), 0) or (
                int(YEAR_PATTERN.search(text).group(1))
                if YEAR_PATTERN.search(text) else self.ref_year
            )
            return Timeframe(quarter=MONTH_TO_QUARTER[month], year=year,
                             month=month, label=m.group(0).strip())

        # --- 4. Relative language, e.g. "last quarter" --------------------
        m = RELATIVE_PATTERN.search(text)
        if m:
            word, unit = m.group(1).lower(), m.group(2).lower()
            direction = {"last": -1, "previous": -1, "prior": -1,
                         "this": 0, "current": 0,
                         "next": 1, "coming": 1}.get(word, 0)
            if unit == "quarter":
                quarter, year = self._shift_quarter(direction)
                return Timeframe(quarter=quarter, year=year, label=m.group(0))
            if unit == "year":
                return Timeframe(year=self.ref_year + direction, label=m.group(0))
            if unit == "month":
                # Approximate a month shift by staying inside the ref quarter.
                quarter, year = self._shift_quarter(0 if direction == 0 else direction)
                return Timeframe(quarter=quarter, year=year, label=m.group(0))

        # --- 5. Period-to-date acronyms ----------------------------------
        m = PTD_PATTERN.search(text)
        if m:
            token = m.group(1).upper()
            quarter, year = self._shift_quarter(0)
            if token == "YTD":
                return Timeframe(year=self.ref_year, label=token)
            return Timeframe(quarter=quarter, year=year, label=token)

        # --- 6. Fiscal year, e.g. "FY2024" -------------------------------
        m = FY_PATTERN.search(text)
        if m:
            return Timeframe(year=self._normalise_year(m.group(1), self.ref_year),
                             label=m.group(0).strip())

        # --- 7. Bare year, e.g. "in 2023" --------------------------------
        m = YEAR_PATTERN.search(text)
        if m:
            return Timeframe(year=int(m.group(1)), label=m.group(1))

        # Nothing found.
        return Timeframe()


