"""
nlp_engine.py
=============

WHAT THIS FILE DOES
-------------------
Turns free-form human text such as::

    "Our European active users hit 984.5k in Q3 2024 and churn fell to 2.1%."

into structured *claims*::

    Claim(raw_value='984.5k', value=984.5, metric_text='european active users',
          metric_column='active_users', region='Europe',
          quarter='Q3', year=2024, context='...')

THE THREE STAGES
----------------
  1. NUMBER EXTRACTION - find every cardinal number / percentage / currency
     amount in the text, together with its character offsets.
  2. CONTEXT HARVESTING - grab a window of characters either side of the
     number (well over the required 10 chars, because real sentences need it)
     and use it to guess the metric name, region and timeframe.
  3. MAPPING - convert the human words ("users", "revenue", "churn") into
     actual database column names via a hardcoded, easily-editable dictionary
     plus substring (fuzzy) matching.

SPACY IS USED WHEN AVAILABLE, REGEX ALWAYS
------------------------------------------
The brief asks for spaCy + ``en_core_web_sm``. We load it ONCE, globally, and
use its CARDINAL / PERCENT / MONEY / DATE / GPE entities to enrich extraction.
But spaCy is a heavy optional dependency: if the model is not downloaded (or
the wheel does not exist for your Python version) the engine automatically
falls back to a pure-regex extractor so the application NEVER fails to start.
``NLPEngine.backend_name`` reports which mode is active and the GUI shows it
in the status bar.

HOW TO EXTEND (read this before editing)
----------------------------------------
* New metric keyword?  Add one line to :data:`METRIC_KEYWORD_MAP`.
    "arr": "annual_recurring_revenue"
* New region?          You do NOT edit this file. Regions are read from your
  database at startup (``SELECT DISTINCT region``); add the row and it is
  recognised. For prose synonyms use ``regions.synonyms`` in config.json.
* New timeframe words? Add to :data:`MONTH_NAMES` or extend
  :func:`TimeframeParser.parse`.
* New number format?   See ``numbers.py`` - it already handles US, European,
  Swiss, Indian and space-separated conventions.
Nothing else needs to change - the rest of the pipeline is generic.
"""

