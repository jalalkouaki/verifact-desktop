# ===========================================================================
# 2. REGIONS - FULLY DYNAMIC, NO HARDCODED GEOGRAPHY
# ===========================================================================
# There is deliberately NO static list of world regions in this file.
#
# Baking in "europe"/"north america"/"apac" made the tool subtly US-centric and,
# worse, useless to anyone whose warehouse uses different labels - sales
# territories, business units, store numbers, legal entities. A hardcoded list
# can only ever be wrong for somebody.
#
# Instead the vocabulary is LEARNED AT STARTUP from the data itself:
#
#     SELECT DISTINCT region FROM financial_metrics
#
# Whatever labels your database actually contains become the labels Veri-Fact
# recognises in prose. If the database is unreachable or empty we fall back to
# ``regions.fallback`` in config.json, which the user controls.
#
# :class:`RegionRegistry` below owns this vocabulary. It also accepts optional
# user-defined SYNONYMS from config.json, e.g.
#
#     "regions": { "synonyms": { "EMEA": ["europe", "european", "eu"] } }
#
# so free-text prose can still map onto whatever canonical label you store.


class RegionRegistry:
    """The set of region labels Veri-Fact will recognise, learned at runtime.

    Built from (in priority order):
      1. ``SELECT DISTINCT region`` from the live database.
      2. ``regions.fallback`` in config.json, when the query yields nothing.
      3. Nothing at all - in which case region detection is simply disabled
         and every lookup runs region-agnostic. That is a safe, neutral
         default rather than a wrong guess.

    Synonyms are optional and entirely user-supplied; the class ships with an
    empty synonym table so no geography is assumed.
    """

    def __init__(self, labels: Optional[Iterable[str]] = None,
                 synonyms: Optional[Dict[str, Iterable[str]]] = None,
                 min_token_length: int = 2) -> None:
        #: canonical label, exactly as stored in the database
        self.labels: List[str] = []
        #: lowercase search term -> canonical label
        self._lookup: Dict[str, str] = {}
        self._pattern: Optional[re.Pattern] = None
        self.min_token_length = max(1, int(min_token_length))
        self.source = "empty"
        self.rebuild(labels or [], synonyms or {})

    # -- construction ------------------------------------------------------
    def rebuild(self, labels: Iterable[str],
                synonyms: Optional[Dict[str, Iterable[str]]] = None,
                source: str = "database") -> None:
        """Replace the vocabulary. Called at startup and after config reload."""
        self.labels = []
        self._lookup = {}

        for label in labels or []:
            text = str(label).strip()
            if not text:
                continue
            if text not in self.labels:
                self.labels.append(text)
            self._register(text, text)
            # A label like "North America" should also match "north_america"
            # and "north-america" as written in code-generated files.
            for variant in self._variants(text):
                self._register(variant, text)

        for canonical, aliases in (synonyms or {}).items():
            target = str(canonical).strip()
            if not target:
                continue
            if target not in self.labels:
                self.labels.append(target)
                self._register(target, target)
            for alias in aliases or []:
                alias_text = str(alias).strip()
                if alias_text:
                    self._register(alias_text, target)

        self._compile()
        self.source = source if self.labels else "empty"

    @staticmethod
    def _variants(label: str) -> List[str]:
        """Punctuation variants of a label that mean the same thing."""
        lowered = label.strip().lower()
        out = {lowered.replace(" ", "_"), lowered.replace(" ", "-"),
               lowered.replace("_", " "), lowered.replace("-", " ")}
        out.discard(lowered)
        return [v for v in out if v]

    def _register(self, term: str, canonical: str) -> None:
        key = str(term).strip().lower()
        # Very short tokens cause false positives inside ordinary words, so we
        # require a minimum length unless the user explicitly configured it.
        if len(key) < self.min_token_length:
            return
        self._lookup.setdefault(key, canonical)

    def _compile(self) -> None:
        """Build one word-boundary regex over the whole vocabulary.

        Word boundaries matter enormously here: a two-letter label like "AU"
        would otherwise fire inside "August". Metric keywords use plain
        substring matching (so "user" catches "active_users"), but region
        labels must match as whole words.
        """
        if not self._lookup:
            self._pattern = None
            return
        terms = sorted(self._lookup, key=len, reverse=True)
        self._pattern = re.compile(
            r"(?<![a-z0-9])(" + "|".join(re.escape(t) for t in terms) +
            r")(?![a-z0-9])",
            re.IGNORECASE,
        )

    # -- queries -----------------------------------------------------------
    @property
    def is_empty(self) -> bool:
        return self._pattern is None

    def canonical(self, term: str) -> Optional[str]:
        return self._lookup.get(str(term).strip().lower())

    def finditer(self, text: str):
        """Yield ``(canonical_label, start, end)`` for every region mention."""
        if self._pattern is None or not text:
            return
        for match in self._pattern.finditer(text):
            label = self.canonical(match.group(1))
            if label:
                yield label, match.start(1), match.end(1)

    def describe(self) -> str:
        if self.is_empty:
            return "no regions loaded (region matching disabled)"
        preview = ", ".join(self.labels[:6])
        more = f" (+{len(self.labels) - 6} more)" if len(self.labels) > 6 else ""
        return f"{len(self.labels)} from {self.source}: {preview}{more}"


