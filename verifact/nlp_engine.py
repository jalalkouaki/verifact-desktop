class NLPEngine:
    """Loads spaCy once (if possible) and extracts claims from text.

    Usage::

        engine = NLPEngine(reference_year=2024, reference_quarter=4)
        claims = engine.extract_claims("Revenue was $4.8M in Q3 2024")

    ``engine.backend_name`` is either ``"spaCy (en_core_web_sm)"`` or
    ``"regex fallback"`` and is surfaced in the GUI status bar so the user
    always knows which extractor produced the results.
    """

    #: The spaCy pipeline is a class attribute so it is genuinely loaded ONCE
    #: for the whole process, no matter how many engines are constructed.
    _nlp = None
    _nlp_load_attempted = False
    _nlp_error = ""

    def __init__(self, reference_year: int = 2024, reference_quarter: int = 4,
                 context_window: int = 90, use_spacy: bool = True,
                 regions: Optional[RegionRegistry] = None,
                 aliases: Optional[Dict[str, str]] = None) -> None:
        self.timeframe_parser = TimeframeParser(reference_year, reference_quarter)
        # Region vocabulary is supplied by the application from the database.
        self.regions = regions if regions is not None else DEFAULT_REGION_REGISTRY
        self.mapper = MetricMapper(regions=self.regions, aliases=aliases)
        # Characters captured on each side of a number. The brief requires at
        # least 10; 90 gives the metric/timeframe detectors real sentences.
        self.context_window = max(10, int(context_window))
        self.use_spacy = use_spacy
        #: Number convention of the document currently being processed. Set by
        #: :meth:`extract_claims`; consulted by the global number parser to
        #: resolve genuinely ambiguous tokens like "1,234".
        self.number_profile: NumberProfile = NumberProfile()
        if use_spacy:
            self._ensure_spacy()

    def set_regions(self, registry: RegionRegistry) -> None:
        """Swap in a new region vocabulary (after a config reload)."""
        self.regions = registry
        self.mapper.regions = registry

    def set_aliases(self, aliases: Dict[str, str]) -> None:
        """Apply learned metric corrections from the smart-suggest store."""
        self.mapper.set_aliases(aliases)

    def register_metrics(self, names: Iterable[str]) -> None:
        """Teach the extractor about DB metrics and derived-metric names."""
        self.mapper.register_metrics(names)

    # -- spaCy bootstrap ---------------------------------------------------
    @classmethod
    def _ensure_spacy(cls) -> None:
        """Import spaCy and load ``en_core_web_sm`` exactly once.

        Any failure (spaCy not installed, model not downloaded, incompatible
        wheel) is captured in ``cls._nlp_error`` and the engine silently
        degrades to the regex extractor.
        """
        if cls._nlp_load_attempted:
            return
        cls._nlp_load_attempted = True
        try:
            import spacy  # type: ignore
            try:
                cls._nlp = spacy.load("en_core_web_sm")
            except OSError:
                cls._nlp_error = (
                    "spaCy is installed but the 'en_core_web_sm' model is missing. "
                    "Run:  python -m spacy download en_core_web_sm"
                )
                cls._nlp = None
        except Exception as exc:
            cls._nlp_error = f"spaCy unavailable ({type(exc).__name__}: {exc})"
            cls._nlp = None

    @property
    def backend_name(self) -> str:
        return "spaCy (en_core_web_sm)" if self._nlp is not None else "regex fallback"

    @property
    def backend_note(self) -> str:
        return self._nlp_error

    # -- helpers -----------------------------------------------------------
    # NOTE: the old ``_to_float`` helper lived here. It assumed US convention
    # (it just stripped commas), which silently mangled "1.234.567,89" into
    # 1.234. It has been replaced entirely by ``numbers.parse_number``, which
    # understands every world convention. Do not reintroduce a local float
    # parser - route all number reading through ``numbers.py``.

    #: Words that are never part of a metric name - stripped when guessing a
    #: candidate phrase for the smart-suggest engine.
    _STOPWORDS = {
        "the", "a", "an", "our", "their", "its", "this", "that", "these",
        "those", "was", "were", "is", "are", "be", "been", "at", "in", "on",
        "of", "for", "to", "and", "or", "but", "with", "by", "from", "as",
        "we", "they", "it", "had", "has", "have", "reached", "hit", "came",
        "reported", "recorded", "stood", "held", "finished", "totalled",
        "totaled", "about", "around", "roughly", "approximately", "up",
        "down", "over", "under", "just", "only", "some", "all", "which",
        "when", "while", "there", "here", "also", "than", "then", "so",
    }

    def _candidate_metric_phrase(self, context: str, number_pos: int,
                                 max_words: int = 3) -> str:
        """Guess the phrase naming an otherwise-unmapped number.

        Looks at the words immediately BEFORE the number (the usual English
        pattern - "customer count was 18400"), falling back to the words after
        it ("18400 customers"). Stopwords and digits are removed and at most
        ``max_words`` content words are returned.

        This never affects mapped claims; it only supplies the smart-suggest
        engine with something to fuzzy-match, turning a silently-dropped
        number into an actionable "Did you mean...?" prompt.
        """
        if not context:
            return ""

        before = context[:max(0, number_pos)]
        after = context[min(len(context), number_pos):]

        # Never reach across a clause boundary. In
        #     "revenu was 4.8M and the custmer count was 18400"
        # the phrase for 18400 must be "custmer count", not
        # "revenu custmer count" - so we keep only the text after the LAST
        # boundary before the number, and up to the FIRST boundary after it.
        boundaries = list(CLAUSE_BOUNDARY_PATTERN.finditer(before))
        if boundaries:
            before = before[boundaries[-1].end():]
        forward = CLAUSE_BOUNDARY_PATTERN.search(after)
        if forward:
            after = after[:forward.start()]

        def content_words(fragment: str, take_last: bool) -> List[str]:
            tokens = re.findall(r"[A-Za-z][A-Za-z_'-]*", fragment)
            words = [t for t in tokens
                     if t.lower() not in self._STOPWORDS and len(t) > 2]
            if not words:
                return []
            return words[-max_words:] if take_last else words[:max_words]

        phrase = content_words(before, take_last=True)
        if not phrase:
            # Skip the number itself, then look forward.
            phrase = content_words(after.lstrip("0123456789.,%$ \t"), take_last=False)

        # Drop a leading region label - "Global revenu" should probe "revenu".
        if phrase and not self.regions.is_empty:
            first = phrase[0]
            if self.regions.canonical(first):
                phrase = phrase[1:] or phrase

        return " ".join(phrase).strip().lower()

    def _context_for(self, text: str, start: int, end: int) -> Tuple[str, int]:
        """Return the surrounding window plus the number's offset inside it.

        Two rules make this window trustworthy:

        1. NEVER CROSS A LINE BREAK. In a log file or a CSV each line is an
           independent record; letting line 4's context reach into line 5 makes
           the metric detector attribute numbers to the wrong row. Line breaks
           are therefore hard walls.
        2. STAY INSIDE THE SENTENCE, on BOTH sides. A number belongs to the
           sentence containing it. Letting the window spill into the next
           sentence is how "churn held at 2.3%. Region_B users were..."
           ends up tagging the churn figure with the wrong region. We trim
           at the nearest sentence terminator in each direction, but never
           below the 10-character minimum the specification requires.
        """
        # Hard wall #1: the enclosing line.
        line_start = text.rfind("\n", 0, start) + 1
        line_end = text.find("\n", end)
        if line_end == -1:
            line_end = len(text)

        left = max(line_start, start - self.context_window)
        right = min(line_end, end + self.context_window)

        # Wall #2a: do not reach back past the previous sentence terminator.
        snippet_left = text[left:start]
        for boundary in (". ", "! ", "? "):
            pos = snippet_left.rfind(boundary)
            if pos != -1 and (start - (left + pos + len(boundary))) >= 10:
                left = left + pos + len(boundary)
                break

        # Wall #2b: do not reach forward past this sentence's terminator.
        # A minimum of 10 trailing characters is preserved so short sentences
        # such as "Revenue was 4.8M." still satisfy the spec's context rule.
        snippet_right = text[end:right]
        best_cut = None
        for boundary in (". ", "! ", "? "):
            pos = snippet_right.find(boundary)
            if pos != -1 and pos >= 10:
                cut = end + pos + 1  # keep the period itself
                best_cut = cut if best_cut is None else min(best_cut, cut)
        if best_cut is not None:
            right = min(right, best_cut)

        raw = text[left:right]
        stripped = raw.lstrip()
        # Keep the offset accurate after stripping leading whitespace.
        number_offset = (start - left) - (len(raw) - len(stripped))
        return stripped.rstrip(), max(0, number_offset)

    @staticmethod
    def _date_token_spans(text: str) -> List[Tuple[int, int]]:
        """Character ranges occupied by date markup such as ``Q3`` or ``FY24``.

        The number scanner skips any match that starts inside one of these
        ranges. Without this, "In Q3 2024 revenue was $4.8M" would produce a
        phantom claim of ``3`` (the quarter digit) alongside the real one.
        """
        return [(m.start(), m.end()) for m in DATE_TOKEN_PATTERN.finditer(text)]

    def _spacy_entities(self, text: str) -> Dict[str, List[str]]:
        """Collect DATE/GPE/ORG entities spaCy found - used to enrich context.

        This is where the spaCy dependency genuinely earns its place: its
        statistical NER catches date phrases ("the third quarter of last year")
        and geo-political entities ("Germany") that our regexes would miss.
        """
        buckets: Dict[str, List[str]] = {"DATE": [], "GPE": [], "LOC": [],
                                         "CARDINAL": [], "PERCENT": [], "MONEY": []}
        if self._nlp is None:
            return buckets
        try:
            doc = self._nlp(text[:100_000])  # guard against pathological input
            for ent in doc.ents:
                if ent.label_ in buckets:
                    buckets[ent.label_].append(ent.text)
        except Exception:
            pass
        return buckets

    # -- THE MAIN EXTRACTION ROUTINE ---------------------------------------
    def extract_claims(self, text: str, source_label: str = "",
                       line_offset: int = 0) -> List[Claim]:
        """Find every numeric claim in ``text``.

        Steps
        -----
        1. Run spaCy (if loaded) once over the text to gather DATE/GPE hints.
        2. Walk every regex number match. For each one:
             a. parse the literal value and any k/M/B/% suffix
             b. carve out a context window (>= 10 chars either side)
             c. ask :class:`MetricMapper` which DB column the context names
             d. ask :class:`TimeframeParser` which period the context names
             e. detect a region word
        3. Skip numbers that are obviously not claims (bare years, list
           indices, numbers with no metric anywhere nearby) to keep the noise
           out of the results table.
        """
        if not text or not text.strip():
            return []

        # STEP 0: work out which number convention this document uses, ONCE.
        # "1,234" means 1234 in a US document and 1.234 in a German one; the
        # token alone cannot tell us, but the document as a whole can.
        self.number_profile = detect_document_profile(text)

        entities = self._spacy_entities(text) if self._nlp is not None else {}
        entity_dates = " ".join(entities.get("DATE", []))
        entity_places = " ".join(entities.get("GPE", []) + entities.get("LOC", []))

        claims: List[Claim] = []
        # Ranges we must not read numbers out of (quarter/half/fiscal markers).
        blocked_spans = self._date_token_spans(text)
        # Pre-compute line numbers so the results table can point at a line.
        line_starts = [0]
        for idx, char in enumerate(text):
            if char == "\n":
                line_starts.append(idx + 1)

        def line_of(pos: int) -> int:
            lo, hi = 0, len(line_starts) - 1
            while lo < hi:
                mid = (lo + hi + 1) // 2
                if line_starts[mid] <= pos:
                    lo = mid
                else:
                    hi = mid - 1
            return lo + 1  # 1-based

        for match in NUMBER_PATTERN.finditer(text):
            raw_number = match.group("number")
            suffix = (match.group("suffix") or "").strip().lower()
            currency = bool(match.group("currency"))

            # Hand the whole token (including any suffix) to the international
            # normalizer, together with the document profile so ambiguous
            # separator patterns resolve consistently across the file.
            parsed: Optional[ParsedNumber] = parse_number(
                match.group(0), self.number_profile)
            if parsed is None:
                continue
            value = parsed.value

            start, end = match.start(), match.end()

            # Skip digits that are part of a date token ("Q3", "H1", "FY24").
            number_start = match.start("number")
            if any(lo <= number_start < hi for lo, hi in blocked_spans):
                continue

            # Skip reference numbers: "slide 3", "page 12", "row 4".
            preceding = text[max(0, number_start - 24):number_start]
            if NOISE_PREFIX_PATTERN.search(preceding):
                continue

            context, number_offset = self._context_for(text, start, end)

            # --- filter out numbers that are clearly not business claims ---
            # A bare 4-digit year that is not followed by a scale suffix is a
            # date, not a metric value.
            if (not suffix and not currency
                    and raw_number.isdigit() and len(raw_number) == 4
                    and 1900 <= value <= 2100):
                continue

            # The normalizer already worked out percent/currency/scale, using
            # a far wider suffix vocabulary (k, M, B, Mio, Mrd, lakh, crore).
            is_percent = parsed.is_percent
            currency = currency or parsed.is_currency
            scale = 1.0 if is_percent else parsed.scale

            # --- metric identification ---
            metric_column, matched_keyword = self.mapper.map_with_position(
                context, number_offset
            )
            if metric_column is None and source_label:
                # For CSV/JSON rows the column header itself is the metric name.
                metric_column, matched_keyword = self.mapper.map_text(source_label)

            # --- timeframe identification ---
            # Search the immediate context first; if that is silent, fall back
            # to spaCy's DATE entities from the wider document.
            timeframe = self.timeframe_parser.parse(context)
            if timeframe.quarter is None and timeframe.year is None and entity_dates:
                timeframe = self.timeframe_parser.parse(entity_dates)
            if timeframe.quarter is None and timeframe.year is None and source_label:
                timeframe = self.timeframe_parser.parse(source_label)

            # --- region identification ---
            # Positional, for the same reason metric matching is positional.
            region = self.mapper.detect_region_with_position(context, number_offset)
            if region is None and source_label:
                region = self.mapper.detect_region(source_label)
            if region is None and entity_places:
                region = self.mapper.detect_region(entity_places)

            # --- unmapped numbers: salvage a candidate name -----------------
            # A number whose metric we cannot map is usually noise (page
            # numbers, IDs) - but it may also be a TYPO or an unfamiliar term
            # ("revenu", "custmer count") that smart-suggest could rescue.
            #
            # So instead of discarding it outright we try to lift the nearest
            # descriptive phrase out of the context. If we find one, the claim
            # survives as AMBER carrying that phrase in ``metric_text``, which
            # is exactly what the suggestion engine fuzzy-matches against.
            # If we find nothing quotable, it really was noise - drop it.
            if metric_column is None and not source_label:
                candidate = self._candidate_metric_phrase(context, number_offset)
                if not candidate:
                    continue
                matched_keyword = candidate

            claims.append(Claim(
                raw_value=match.group(0).strip(),
                value=value,
                scale=scale,
                is_percent=is_percent,
                is_currency=currency,
                context=context,
                metric_text=matched_keyword or source_label,
                metric_column=metric_column,
                region=region,
                timeframe=timeframe,
                char_start=start,
                char_end=end,
                line_no=line_of(start) + line_offset,
                source_label=source_label,
                extraction_backend=self.backend_name,
                ambiguous_format=parsed.ambiguous,
                alternative_values=[a * scale for a in parsed.alternatives],
                number_profile=parsed.profile,
            ))

        return claims

    def extract_from_value(self, value: float, label: str, context: str,
                           line_no: int = 0) -> Claim:
        """Build a claim from an already-numeric input (CSV cell / JSON value).

        No regex needed here - pandas already handed us a float. We still run
        the metric mapper and timeframe parser over the label and the row's
        text context, which is exactly what the brief asks for when it says a
        CSV row should be treated as one claim using its header plus adjacent
        text.
        """
        blob = f"{label} {context}"
        metric_column, matched = self.mapper.map_text(label)
        if metric_column is None:
            metric_column, matched = self.mapper.map_text(blob)

        timeframe = self.timeframe_parser.parse(blob)
        region = self.mapper.detect_region(blob)

        # The caller may hand us a STRING cell that pandas left untyped, e.g.
        # a European CSV column holding "1.234,56". Run it through the global
        # normalizer rather than assuming it is already a clean float.
        scale = 1.0
        numeric = value
        alternatives: List[float] = []
        ambiguous = False
        profile_name = self.number_profile.name

        if not isinstance(value, (int, float)) or isinstance(value, bool):
            parsed = parse_number(str(value), self.number_profile)
            if parsed is None:
                numeric = 0.0
            else:
                numeric = parsed.value
                scale = parsed.scale
                alternatives = [a * scale for a in parsed.alternatives]
                ambiguous = parsed.ambiguous
                profile_name = parsed.profile

        return Claim(
            raw_value=str(value),
            value=float(numeric),
            scale=scale,
            is_percent="%" in label or "rate" in label.lower(),
            is_currency=any(sym in label for sym in "$€£¥₹₽₩"),
            context=context.strip()[:400],
            metric_text=matched or label,
            metric_column=metric_column,
            region=region,
            timeframe=timeframe,
            line_no=line_no,
            source_label=label,
            extraction_backend=self.backend_name,
            ambiguous_format=ambiguous,
            alternative_values=alternatives,
            number_profile=profile_name,
        )
