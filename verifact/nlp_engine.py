# ===========================================================================
# REGEX: the workhorse number finder  (INTERNATIONAL)
# ===========================================================================
# This pattern only has to FIND numeric tokens; interpreting them is the job of
# ``numbers.parse_number``, which understands every world convention. So the
# pattern is deliberately permissive about separators and lets the normalizer
# decide what is a thousands group and what is a decimal point.
#
# Matches:  1,234,567.89   1.234.567,89   1'234'567.89   12,34,567.89
#           1 234 567,89   1234.56   $4.8M   98,5%   -12   (2.3)   ₹5 lakh
NUMBER_PATTERN = re.compile(
    r"""
    (?P<currency>[$€£¥₹₽₩¢₪₺]\s?)?           # optional leading currency symbol
    (?P<number>
        (?<![\w.,'-])
        -?\d{1,3}                            # leading group (1-3 digits)
        (?:[,.\u00a0\u202f\u2009' ]\d{2,3})+ # further groups of 2 (Indian) or 3
        (?:[.,]\d+)?                         # optional decimal tail
      | (?<![\w.,'-])-?\d+[.,]\d+            # 1234.56  or  1234,56
      | (?<![\w.,'-])-?\d+                   # 1234
    )
    [ \t]?                                   # NOT \s - a newline must never be
                                             # swallowed, or the per-line
                                             # context wall below breaks.
    (?P<suffix>%|percent|pct|k\b|m\b|mm\b|mio\b|mrd\b|bn?\b|tn?\b
        |thousand|million|billion|trillion|lakhs?|lacs?|crores?|cr\b)?
    """,
    re.IGNORECASE | re.VERBOSE,
)
# The ``(?<![\w.,'-])`` guard stops us slicing fragments out of the middle of
# compound tokens. Without it the log timestamp ``2024-10-02`` would yield the
# three "numbers" 2024, -10 and -02, and "1.234.567" would yield "1.234".

# Standalone quarter tokens: Q1 / q4 2024 / Q3'24
QUARTER_PATTERN = re.compile(r"\bQ([1-4])\b(?:\s*[,']?\s*(\d{2,4}))?", re.IGNORECASE)
# Spans that are DATE MARKUP, not claims. The digit in "Q3", the "1" in "H1"
# and the "24" in "FY24" must never be reported as a numeric assertion, so we
# blank these regions out before the number scanner runs. See
# ``_date_token_spans`` below.
DATE_TOKEN_PATTERN = re.compile(
    r"""
      \bQ[1-4]\b                              # Q3
    | \bH[12]\b                                # H1
    | \b(?:FY|fiscal(?:\s+year)?)\s*'?\d{2,4}\b  # FY2024
    | \b\d{4}-\d{2}-\d{2}\b                    # 2024-10-02  (ISO date)
    | \b\d{2}/\d{2}/\d{2,4}\b                  # 02/10/2024
    | \b\d{1,2}:\d{2}(?::\d{2})?\b             # 09:14:11    (clock time)
    | \bv\d+\.\d+(?:\.\d+)?\b                  # v1.2.3      (version, needs 'v')
    | (?<![\d.])\d{1,2}\.\d{1,2}\.\d{1,2}(?![\d.])  # 1.2.3   (bare version)
    """,
    re.IGNORECASE | re.VERBOSE,
)
# CAREFUL with the version-number rule above. An earlier draft used the
# permissive ``\d+\.\d+\.\d+`` and it silently ate every European-formatted
# number: "4.800.000,00" looks exactly like a version string. The groups are
# now capped at 1-2 digits each and guarded by lookarounds, so real versions
# (1.2.3) still match while thousands-grouped amounts (4.800.000) do not.
# Half-year: H1 / H2 2025
HALF_PATTERN = re.compile(r"\bH([12])\b(?:\s*(\d{2,4}))?", re.IGNORECASE)
# Fiscal year: FY2024 / FY 24 / fiscal 2024
FY_PATTERN = re.compile(r"\b(?:FY|fiscal(?:\s+year)?)\s*'?(\d{2,4})\b", re.IGNORECASE)
# Bare 4-digit year 2000-2099
YEAR_PATTERN = re.compile(r"\b(20\d{2})\b")
# Month name optionally followed by a year
MONTH_PATTERN = re.compile(
    r"\b(" + "|".join(sorted(MONTH_NAMES, key=len, reverse=True)) + r")\b"
    r"(?:\s+(?:of\s+)?'?(\d{2,4}))?",
    re.IGNORECASE,
)
# Relative expressions
RELATIVE_PATTERN = re.compile(
    r"\b(last|previous|prior|this|current|next|coming)\s+"
    r"(quarter|month|year|week)\b",
    re.IGNORECASE,
)
# Period-to-date acronyms
PTD_PATTERN = re.compile(r"\b(YTD|MTD|QTD)\b", re.IGNORECASE)

# Words that mean "the number after me is a reference, not a measurement":
# "slide 3", "page 12", "row 4", "version 2", "item #7". Numbers introduced by
# these are silently dropped so a slide deck's own pagination never appears in
# the results table.
NOISE_PREFIX_PATTERN = re.compile(
    r"\b(slide|page|pg|line|row|record|item|step|chapter|figure|fig|table|tab|"
    r"section|part|version|ver|v|no|num|number|id|ref|column|col|note|"
    r"appendix|exhibit|question|q)\b[\s.:#]*$",
    re.IGNORECASE,
)

# Boundaries that separate one clause from the next. A metric keyword on the
# far side of one of these is much less likely to describe our number, so the
# scorer charges a penalty for each boundary crossed. This is what makes
#   "revenue was $4.8M, and the churn rate held at 2.3%"
# attach 4.8M to revenue rather than to churn.
CLAUSE_BOUNDARY_PATTERN = re.compile(
    r"[,;:|]|\band\b|\bwhile\b|\bbut\b|\bhowever\b|\bwhereas\b|\bplus\b|\n",
    re.IGNORECASE,
)

# A full stop is a far stronger separator than a comma: a metric or region
# mentioned in the PREVIOUS sentence almost never describes this number.
SENTENCE_BOUNDARY_PATTERN = re.compile(r"[.!?](?:\s|$)|\n")

# How much a single clause boundary costs, expressed in "characters of
# distance". Tune this if matching feels too eager or too timid.
CLAUSE_PENALTY = 60.0
# Crossing a sentence end costs far more.
SENTENCE_PENALTY = 400.0

# If the best region candidate scores worse than this it is discarded and the
# claim is treated as region-less (which makes the database fall back to the
# 'Global' row). Without a floor, a single "North American" at the top of a
# paragraph would be stamped onto every unrelated number below it.
REGION_SCORE_LIMIT = 160.0


